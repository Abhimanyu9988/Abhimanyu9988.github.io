#!/usr/bin/env python3
"""Remove the footer and stray quotes this project's Claude session adds to issue and PR text.

Abhi doesn't want the footer, and the session can't turn it off. Only the end of the text and those exact quotes change.
"""
import json, os, re, subprocess, sys

FOOTER = re.compile(r"\s*(?:^---\s*)?^_Generated by \[Claude Code\]\(https://claude\.ai/code[^)\s]*\)_\s*\Z", re.M)
QUOTES = re.compile(r"``''(?=https://)")

def clean(body):
    return QUOTES.sub("", FOOTER.sub("\n", body or ""))

def gh(*args, data=None):
    return subprocess.run(["gh", "api", *args], input=data, capture_output=True, text=True, check=True).stdout

def fix(repo, number, body):
    new = clean(body)
    if new != (body or ""):
        gh("-X", "PATCH", f"repos/{repo}/issues/{number}", "--input", "-", "--silent", data=json.dumps({"body": new}))
        print(f"cleaned #{number}")

def main():
    repo = os.environ["GITHUB_REPOSITORY"]
    number = os.environ.get("NUMBER") or ""
    if number:
        fix(repo, number, json.loads(gh(f"repos/{repo}/issues/{number}")).get("body"))
        return 0
    for line in gh("--paginate", f"repos/{repo}/issues?state=all&per_page=100", "--jq", ".[]|{number,body}|@json").splitlines():
        row = json.loads(line)
        fix(repo, row["number"], row["body"])
    return 0

if __name__ == "__main__":
    sys.exit(main())
