#!/usr/bin/env bash
# BEFORE and the problem. The gateway Collector takes 60 single-span requests a second, and its export target (the relay)
# goes away for 30 s. batch-1 and batch-2 run the batch processor with its defaults and the default sending_queue. Then
# migrated-1 and migrated-2 make the one-line migration from the OpenTelemetry blog: no batch processor, sending_queue batch
# enabled, the queue left at its defaults. Every count comes from the gateway's own metrics.
# Reproduced when the exporter fails to enqueue spans in both migrated runs and in neither batch run. Refused attempts and
# spans lost (generated by the sender, never sent by the gateway) are printed per run. fix.sh sizes the queue in items.
set -uo pipefail
cd "$(dirname "$0")"
. ./lib.sh
. ./measure.sh

start_clock 820 not_reproduced

aws eks update-kubeconfig --name "$(terraform output -raw cluster_name)" --region "$AWS_REGION" >/dev/null || fail "could not write kubeconfig"
for v in SPLUNK_REALM SPLUNK_ACCESS_TOKEN SPLUNK_API_TOKEN; do [ -n "${!v:-}" ] || fail "$v is not set"; done

echo "== 1. Waiting for 2 worker nodes"
ready=0
t0=$(date +%s)
while [ $(( $(date +%s) - t0 )) -lt 300 ]; do
  ready=$(kubectl --request-timeout=15s get nodes --no-headers 2>/dev/null | grep -c ' Ready' || true)
  [ "${ready:-0}" -ge 2 ] && break
  sleep 10
done
kubectl --request-timeout=15s get nodes --no-headers -o custom-columns=NAME:.metadata.name,TYPE:.metadata.labels.node\.kubernetes\.io/instance-type,READY:.status.conditions[-1].type || true
[ "${ready:-0}" -ge 2 ] || fail "nodes did not become Ready"
kubectl -n kube-system rollout status deploy/coredns --timeout="$(cap 90 600)s" >/dev/null || true

# The gateway and the relay stay on one node, the load and the stats pod on the other, in every run.
APP_NODE=$(kubectl get nodes -o jsonpath='{.items[0].metadata.name}')
LOAD_NODE=$(kubectl get nodes -o jsonpath='{.items[1].metadata.name}')
echo "$APP_NODE" > app-node.txt
echo "$LOAD_NODE" > load-node.txt
echo "app node: $APP_NODE; load node: $LOAD_NODE"

echo "== 2. Installing the Splunk OTel Collector (chart 0.163.1), the same in every run"
for i in 1 2 3; do
  helm repo add splunk-otel-collector-chart https://signalfx.github.io/splunk-otel-collector-chart >/dev/null 2>&1 && helm repo update >/dev/null 2>&1 && break
  sleep 10
done
helm upgrade --install splunk-otel-collector splunk-otel-collector-chart/splunk-otel-collector \
  --version 0.163.1 --namespace splunk --create-namespace \
  --set splunkObservability.realm="$SPLUNK_REALM" \
  --set splunkObservability.accessToken="$SPLUNK_ACCESS_TOKEN" \
  --set clusterName="$LAB_NAME" \
  --set cloudProvider=aws \
  --set distribution=eks \
  >/dev/null || fail "collector install failed"
kubectl -n splunk rollout status daemonset/splunk-otel-collector-agent --timeout="$(cap 150 560)s" >/dev/null || fail "collector agent not ready"
echo "collector agent ready on $(kubectl -n splunk get daemonset splunk-otel-collector-agent -o jsonpath='{.status.numberReady}') nodes"

echo "== 3. Deploying the gateway and the relay (contrib 0.165.0) and the stats pod"
kubectl create namespace demo --dry-run=client -o yaml | kubectl apply -f - >/dev/null
sed -e "s/APP_NODE/$APP_NODE/" -e "s/LOAD_NODE/$LOAD_NODE/" k8s/30-gateway.yaml | kubectl apply -f - >/dev/null || fail "could not deploy the gateway"
kubectl -n demo rollout status deploy/relay --timeout="$(cap 120 520)s" >/dev/null || { why relay; fail "the relay did not start"; }
kubectl -n demo rollout status deploy/gateway --timeout="$(cap 120 510)s" >/dev/null || { why gateway; fail "the gateway did not start"; }
kubectl -n demo wait pod/stats --for=condition=Ready --timeout="$(cap 120 500)s" >/dev/null || fail "the stats pod is not ready"
echo "effective gateway configs:"
kubectl -n demo get configmap gateway -o jsonpath='{.data.batch\.yaml}' | sed -n '/^processors/,/^service/p' | sed 's/^/  batch.yaml    | /'
kubectl -n demo get configmap gateway -o jsonpath='{.data.migrated\.yaml}' | sed -n '/^exporters/,/^service/p' | sed 's/^/  migrated.yaml | /'

rm -f runs.txt results.txt
for r in batch-1 migrated-1 batch-2 migrated-2; do
  echo "== Run $r: ${r%-*}.yaml, 50 s of load, the relay down from 10 s to 40 s"
  start_run "$r" 120
  outage_run "$r"
  measures "$r"
done

echo "== Summary"
summary

ok=1
for r in batch-1 batch-2; do [ "$(col "$r" 5)" = 0 ] || ok=0; done
for r in migrated-1 migrated-2; do [ "$(col "$r" 5)" -gt 0 ] || ok=0; done
[ "$ok" = 1 ] && emit reproduced || emit not_reproduced
