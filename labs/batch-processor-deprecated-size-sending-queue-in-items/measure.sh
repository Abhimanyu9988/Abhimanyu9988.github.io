# Shared by fix.sh and reproduce.sh, sourced after lib.sh: the per-run counts, the summary and the Splunk APM read.

gwd() {   # run label, count name: end minus start
  local a b; a=$(sed -n "s/^GW $2=//p" "gw-$1-start.txt"); b=$(sed -n "s/^GW $2=//p" "gw-$1-end.txt")
  awk -v a="${a:-0}" -v b="${b:-0}" 'BEGIN { printf "%.0f", b - a }'
}

traces() {   # run label: traces the load's 4 workers say they generated
  grep 'traces generated' "load-$1.txt" | grep -oE '"traces": ?[0-9]+|traces=[0-9]+' | grep -oE '[0-9]+$' | awk '{t += $1} END {printf "%.0f", t}'
}

# From the watcher's 2 s reads: accepted spans a second between 2 s and 10 s into the load (before the outage), the
# highest queue size before the outage, and seconds from the relay's return (its scale-up command, so the relay's rollout
# is included) until the queue is back at or below that level and stays there for 3 reads in a row.
watch_figures() {   # run label. Sets rate, pre_peak, drained.
  local t_load t_down t_up
  read -r _ t_load _ t_down t_up < <(awk -v r="$1" '$1 == r' runs.txt)
  read -r rate pre_peak drained < <(awk -v l="$t_load" -v d="$t_down" -v u="$t_up" '
    { t = $2; for (i = 3; i <= NF; i++) { split($i, kv, "="); v[kv[1]] = kv[2] + 0 }
      if (t >= l + 2 && a0 == "") { a0 = v["accepted"]; t0 = t }
      if (t <= l + 10) { a1 = v["accepted"]; t1 = t }
      if (t < d && v["size"] > pp) pp = v["size"]
      if (t >= u && dr == "") { if (v["size"] <= pp + 0) { if (++low == 1) first = t; if (low >= 3) dr = first - u } else low = 0 } }
    END { r = (t1 > t0) ? (a1 - a0) / (t1 - t0) : 0; printf "%.1f %.0f %s\n", r, pp + 0, (dr == "" ? -1 : dr) }' "q-$1.txt")
}

measures() {   # run label: the sender's count, the gateway's counts, and its queue during the run
  local gen tr acc ref enq sent sfail lost peak capa workers
  tr=$(traces "$1"); gen=$(( ${tr:-0} * 2 )); workers=$(grep -c 'traces generated' "load-$1.txt")
  watch_figures "$1"
  acc=$(gwd "$1" accepted); ref=$(gwd "$1" refused); enq=$(gwd "$1" enqueue_failed); sent=$(gwd "$1" sent)
  sfail=$(gwd "$1" send_failed); lost=$(( ${gen:-0} - sent ))
  peak=$(awk '{sub("size=", "", $3); if ($3 + 0 > m) m = $3 + 0} END {printf "%.0f", m}' "q-$1.txt")
  capa=$(awk '{sub("capacity=", "", $4); if ($4 + 0 > m) m = $4 + 0} END {printf "%.0f", m}' "q-$1.txt")
  echo "$1 load: $(grep -oE '"per-second": ?[0-9.]+' "load-$1.txt" | head -1) per worker; traces per worker: $(grep 'traces generated' "load-$1.txt" | grep -oE '"traces": ?[0-9]+' | grep -oE '[0-9]+$' | tr '\n' ' ')"
  echo "$1 queue reads: $(wc -l < "q-$1.txt"), highest size $peak of $capa (before the outage: $pre_peak); accepted $rate spans/s from 2 s to 10 s into the load"
  echo "$1: the load generated $tr traces = $gen spans ($workers workers reported, 2 spans a trace); the gateway accepted $acc, refused $ref attempts, failed to enqueue $enq, sent $sent; export attempts failed $sfail; generated but never sent $lost (generated - sent); drain target $drain_target, complete $drain_complete; queue back to its pre-outage level ${drained}s after the relay returned (-1: not within the reads)"
  echo "HERO_MEASURE: load_spans_generated[$1]=${gen:-0}"
  echo "HERO_MEASURE: gateway_spans_accepted[$1]=$acc"
  echo "HERO_MEASURE: gateway_accept_rate[$1]=$rate"
  echo "HERO_MEASURE: gateway_spans_refused[$1]=$ref"
  echo "HERO_MEASURE: gateway_enqueue_failed[$1]=$enq"
  echo "HERO_MEASURE: gateway_spans_sent[$1]=$sent"
  echo "HERO_MEASURE: queue_peak[$1]=$peak"
  echo "$1 queue capacity: $capa"
  echo "HERO_MEASURE: seconds_to_drain[$1]=$drained"
  echo "HERO_MEASURE: drain_complete[$1]=$drain_complete"
  echo "$1 ${gen:-0} $acc $ref $enq $sent $lost $peak $capa $rate $drained $drain_complete" >> results.txt
  [ "$workers" = 4 ] || fail "$1: $workers of 4 load workers reported a count, so the sender's total isn't known"
  [ "$acc" -gt 0 ] || fail "the gateway accepted no spans in $1"
  [ "$sfail" -gt 0 ] || [ "$enq" -gt 0 ] || [ "$ref" -gt 0 ] || echo "note: $1 saw no failed export attempt, so the outage may not have reached the gateway"
}

# results.txt columns: 1 run, 2 generated, 3 accepted, 4 refused, 5 enqueue failed, 6 sent, 7 lost, 8 queue peak, 9 capacity,
# 10 accept rate, 11 seconds to drain, 12 drain complete.
col() { awk -v r="$1" -v c="$2" '$1 == r {print $c}' results.txt; }   # run, column number
summary() {
  printf '%-11s %9s %7s %9s %8s %9s %8s %6s %7s %9s %8s %9s\n' run generated rate/s accepted refused enq_fail sent lost peak capacity drain_s complete
  while read -r r a b c d e f g h i j k; do printf '%-11s %9s %7s %9s %8s %9s %8s %6s %7s %9s %8s %9s\n' "$r" "$a" "$i" "$b" "$c" "$d" "$e" "$f" "$g" "$h" "$j" "$k"; done < results.txt
  echo "(refused counts attempts: the sender may retry a refused request. lost = generated by the sender - sent by the gateway.)"
}

# Sums every point SignalFlow returns between start and stop (10 s resolution), across all series.
sf_total() {   # program, start s, stop s. Read up to 3 times if the stream comes back empty.
  local out n
  for try in 1 2 3; do
    out=$(signalflow "$1" "$(( $2 * 1000 ))" "$(( $3 * 1000 ))")
    [ -n "$out" ] && break
    sleep 5
  done
  n=$(awk '{t += $2} END {printf "%.0f", t}' <<<"$out")
  echo "${n:-0}"
}

# Spans Splunk APM counts for the load service from a run's load start to 20 s after its drain, in whole 10 s points.
apm_spans() {   # run label
  local s e f n
  s=$(awk -v r="$1" '$1 == r {print $2}' runs.txt); e=$(awk -v r="$1" '$1 == r {print $3}' runs.txt)
  s=$(( s / 10 * 10 )); e=$(( (e + 20 + 9) / 10 * 10 ))
  f="filter('sf_environment', '$LAB_NAME') and filter('sf_service', 'checkout-load')"
  apm_program="data('spans.count', filter=$f, rollup='delta').sum().publish()"
  n=$(sf_total "$apm_program" "$s" "$e")
  # Orgs on histogram MetricSets hold the count as histogram('spans'), so that form is read too when the first is empty.
  if [ "$n" = 0 ]; then apm_program="histogram('spans', filter=$f).count().publish()"; n=$(sf_total "$apm_program" "$s" "$e"); fi
  apm_window="$(date -u -d @"$s" +%H:%M:%S)-$(date -u -d @"$e" +%H:%M:%S) UTC"
  echo "$n"
}

apm_program_for() {   # the first program apm_spans tries, as printed next to each count
  echo "data('spans.count', filter=filter('sf_environment', '$LAB_NAME') and filter('sf_service', 'checkout-load'), rollup='delta').sum().publish() (histogram('spans', ...).count() if that reads 0)"
}
